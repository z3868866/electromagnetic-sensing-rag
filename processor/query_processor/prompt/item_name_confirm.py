# processor/query_processor/prompt/item_name_confirm.py

ITEM_NAME_EXTRACT_SYSTEM_PROMPT = "你是一个专业的电磁感知知识库助手，擅长理解用户意图和提取关键信息。"

ITEM_NAME_EXTRACT_TEMPLATE = """
历史会话：
{history_text}

当前用户问题：
{query}

请根据历史会话和当前问题，提取用户正在询问的文献名称（item_names）。
判定规则：
1. 文献名称包括：论文标题、方法名称、模型名称、技术或算法名称。它可能出现在句首、句中或句末，即使嵌在完整句子里，也要原样提取。
2. 如果用户明确提到了文献或方法名称，请提取出来。可能有一个或多个，但不能重复。
3. 如果用户使用了代词（如"这个"、"它"、"该方法"），请结合历史会话做指代消解，确定其指代的文献名称。
4. 只要问题涉及任何具体的论文、方法、模型或技术名称，就必须提取，不要轻易返回空列表；只有当问题完全不涉及任何具体文献或方法（例如纯闲聊"今天天气怎么样"）时，item_names 才返回空列表。
5. 请重新改写用户的问题（rewritten_query），补全文献名称，使其成为脱离上下文也能理解的独立完整问题。

示例：
问题：基于深度卷积神经网络的协作频谱感知方法是如何缓解梯度消失的？
item_names：["基于深度卷积神经网络的协作频谱感知方法"]
rewritten_query：基于深度卷积神经网络的协作频谱感知方法是如何缓解梯度消失的？

请直接返回JSON格式结果，格式如下：
{{
    "item_names": ["文献A", "文献B"],
    "rewritten_query": "关于文献A和文献B，..."
}}
"""